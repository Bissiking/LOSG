await game.locator('[data-action=acknowledge]').waitFor();
assert.equal(await game.locator('#sb-deaths').textContent(),'0');
results.push('closing and relaunching the LOSG iframe restores the warning and a fresh session');
results.push('LOSG catalogue launch, system pause freeze and automatic resume');
assert.deepEqual(errors,[]);
console.log(JSON.stringify({results,errors},null,2));
writeFileSync('.cache/shiftbreak/browser-results.json',JSON.stringify({base,results,errors},null,2));
